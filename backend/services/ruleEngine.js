/**
 * 根据诊断结果返回防控建议
 *
 * @param {Array}  diagnosis   — ruleBasedDiagnosis 返回的结果数组
 * @param {Object} environment — 环境数据
 * @returns {Object} { primary: {...}, secondary: [...], generalAdvice: [...] }
 */
function ruleBasedAdvice(diagnosis, environment) {
  if (!diagnosis || diagnosis.length === 0) {
    return {
      primary: null,
      secondary: [],
      generalAdvice: [
        '建议联系专业兽医进行现场诊断',
        '收集更多症状信息后再次尝试诊断',
        '注意观察禽群精神状态、采食量和粪便变化'
      ]
    };
  }

  const primary = diagnosis[0];
  const secondary = diagnosis.slice(1);

  // 通用防控建议
  const generalAdvice = [
    '立即隔离可疑病禽，减少与健康禽群接触',
    '加强禽舍消毒，每日 1-2 次',
    '密切监测禽群精神状态、采食量、饮水量和粪便变化',
    '保持适宜的温湿度和通风条件',
    '保证清洁饮水和全价饲料供应',
    '做好病死禽无害化处理',
    '详细记录发病时间、症状变化和采取措施'
  ];

  // 根据环境条件追加针对性建议
  if (environment) {
    if (environment.temperature > 30) {
      generalAdvice.push('当前温度偏高，加强通风降温，提供清凉饮水，防止热应激');
    }
    if (environment.temperature < 15) {
      generalAdvice.push('当前温度偏低，加强保温措施，防止冷应激');
    }
    if (environment.humidity > 75) {
      generalAdvice.push('当前湿度偏高，加强通风除湿，防止病原微生物滋生');
    }
    if (environment.ammonia > 15) {
      generalAdvice.push('氨气浓度偏高，立即加强通风，清理粪便');
    }
  }

  return {
    primary,
    secondary,
    generalAdvice
  };
}

