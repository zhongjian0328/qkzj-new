/**
 * 基于关键词规则的诊断引擎
 *
 * @param {string|string[]} symptoms    — 症状描述字符串或症状数组
 * @param {Array}           images      — 图像分析结果 [{ description, keywords }]
 * @param {Object}          environment — 环境数据 { temperature, humidity, ammonia, ... }
 * @returns {Array} 按置信度降序排列的诊断结果数组（Top 3）
 */
function ruleBasedDiagnosis(symptoms, images, environment) {
  // 统一处理症状输入为字符串
  const symptomText = Array.isArray(symptoms)
    ? symptoms.join(' ')
    : (symptoms || '');

  // 收集图像分析中的视觉关键词
  const imageKeywords = [];
  if (images && Array.isArray(images)) {
    images.forEach(img => {
      if (img.description) {
        imageKeywords.push(img.description);
      }
      if (img.keywords && Array.isArray(img.keywords)) {
        imageKeywords.push(...img.keywords);
      }
      // 兼容百度图像分析格式
      if (img.result && Array.isArray(img.result)) {
        img.result.forEach(r => {
          if (r.keyword) imageKeywords.push(r.keyword);
          if (r.baike_info && r.baike_info.description) imageKeywords.push(r.baike_info.description);
        });
      }
    });
  }

  // 合并所有输入文本
  const fullText = [symptomText, ...imageKeywords].join(' ');

  // 计算每条规则的匹配得分
  const scores = DISEASE_RULES.map(rule => {
    let matchedKeywords = [];
    let totalWeight = 0;

    for (const [keyword, weight] of Object.entries(rule.weights)) {
      if (fullText.includes(keyword)) {
        matchedKeywords.push(keyword);
        totalWeight += weight;
      }
    }

    // 环境因素微调
    let envModifier = 0;
    if (environment) {
      // 潮湿环境增加球虫病权重
      if (environment.humidity > 70 && rule.disease.includes('球虫')) {
        envModifier += 0.05;
      }
      // 温差大增加呼吸道疾病权重
      if (environment.temperatureFluctuation && rule.disease.match(/新城疫|传支|支原体/)) {
        envModifier += 0.03;
      }
      // 氨气高增加呼吸道疾病权重
      if (environment.ammonia > 15 && rule.disease.match(/支原体|传支|大肠杆菌/)) {
        envModifier += 0.03;
      }
      // 低温增加应激性疾病权重
      if (environment.temperature < 15 && rule.disease.match(/传支|沙门氏菌/)) {
        envModifier += 0.02;
      }
    }

    const confidence = Math.min(totalWeight + envModifier, 1.0);

    return {
      disease: rule.disease,
      confidence: parseFloat(confidence.toFixed(3)),
      matchedSymptoms: matchedKeywords,
      recommendations: rule.recommendations,
      greenMedication: rule.greenMedication
    };
  });

  // 过滤低于阈值的，按置信度降序排列，取 Top 3
  return scores
    .filter(s => s.confidence >= 0.15)
    .sort((a, b) => b.confidence - a.confidence)
    .slice(0, 3);
}

